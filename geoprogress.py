b=int(input()) #первый член геом прогрессии
q=int(input()) #множитель прогрессии
n=int(input()) #номер последнего элемента прогрессии
if -10000<=b<=10000 and q==1 and 2<=n<=100 :
    print(b*n) #считает сумму геом прогрессии если q равно 1
elif -10000<=b<=10000 and 1<q<=50 and 2<=n<=100 :
    print((b*((q**n)-1))/(q-1)) #считает сумму геом прогрессии если q не равно 1
else :
    print("Введите другие значения")