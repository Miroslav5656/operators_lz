n=int(input("Здравствуйте!Введите число от 1 до 100000:"))
b=0
if 1<=n<=100000 :
    while n>0 : #циклы в которых отнимается 3 пока число не станет меньше или равно 0
        n-=3 #отнимается от n 3
        b+=1 #добавляется кол-во операций по 1 за цикл
    print(b)
else :
    print("Введите другое значение")