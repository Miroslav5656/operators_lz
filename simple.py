n=int(input("Здравствуйте!Введите число от 1 до 25:"))
f=0
if 1<=n<=25:
    for r in range (2,n): #цикл для поиска делителей
        if n%r==0: 
            f+=1
    if n>1 and f==0: #проверка то есть если число больше 1 и нет делителей f то оно простое если не выполняется то число не простое
        print(n,"-Y(простое число)")
    else:
        print(n,"-N(не простое число)")
else :
    print ("Введите другое значение")